"""«Мои игры» для окна программы: список игр с состоянием русификации (кэш + фоновый поиск)."""

from __future__ import annotations

import json
import logging
import re
import threading
import time
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

from .. import library, paths
from ..core.backup import GameBackup

log = logging.getLogger("russificator.games")

LIVE_FILE = "BepInEx/Translation/ru/Text/_AutoGeneratedTranslations.txt"


def live_count(game: Path) -> int:
    """Сколько строк перевела живая «доводка» в игре (Unity/XUnity) — насколько далеко заранее
    подготовленный перевод от 100 %."""
    f = Path(game) / LIVE_FILE
    try:
        with f.open("r", encoding="utf-8", errors="replace") as fh:
            return sum(1 for line in fh if "=" in line and not line.lstrip().startswith("//"))
    except OSError:
        return 0


#: все поля состояния — status() отдаёт их всегда, чтобы обновление записи игры (здесь и в окне)
#: затирало прежние значения, а не оставляло, например, «перевод слетел» после отката
_NOT_RUSSIFIED: Dict[str, Any] = {"russified": False, "intact": None, "broken": 0, "from_package": False,
                                  "translator": "", "date": "", "translated": None, "total": None, "live": 0}


def status(game: Path) -> Dict[str, Any]:
    """Состояние русификации папки игры (быстро: манифест бэкапа и stat файлов)."""
    from ..core.package import translator_title
    b = GameBackup(Path(game))
    if not b.exists:
        return dict(_NOT_RUSSIFIED)
    ok, broken = b.check()
    info = b.info or {}
    pkg = info.get("package") or {}
    return {
        "russified": True, "intact": ok, "broken": len(broken), "from_package": bool(pkg),
        "translator": pkg.get("translator") if pkg else translator_title(str(info.get("translator", ""))),
        "date": info.get("date") or info.get("installed") or "",
        "translated": info.get("translated"), "total": info.get("total"),
        "live": live_count(Path(game)),
    }


def russified_dirs() -> List[str]:
    """Папки игр из проектов программы (что уже переводилось)."""
    out = []
    for f in paths.sub("projects").glob("*/project.json"):
        try:
            with f.open("r", encoding="utf-8") as fh:
                head = fh.read(4096)
            m = re.search(r'"game_dir"\s*:\s*"((?:[^"\\]|\\.)*)"', head)
            if m:
                out.append(json.loads(f'"{m.group(1)}"'))
        except (OSError, ValueError):
            continue
    return out


class Library:
    """Список игр: мгновенно из кэша, свежий — фоновым поиском."""

    def __init__(self, emit: Callable[[Dict[str, Any]], None]):
        self.emit = emit
        self._lock = threading.Lock()
        self._thread: Optional[threading.Thread] = None
        self.games: List[Dict[str, Any]] = []
        self.scanned_at = 0.0
        self._load_cache()

    @property
    def cache_file(self) -> Path:
        return paths.cache_dir() / "library.json"

    @property
    def scanning(self) -> bool:
        return self._thread is not None and self._thread.is_alive()

    def _load_cache(self) -> None:
        try:
            data = json.loads(self.cache_file.read_text(encoding="utf-8"))
            self.games = [g for g in data.get("games", []) if isinstance(g, dict) and g.get("path")]
            self.scanned_at = float(data.get("scanned_at", 0))
        except (OSError, ValueError):
            self.games, self.scanned_at = [], 0.0

    def _save_cache(self) -> None:
        try:
            tmp = self.cache_file.with_suffix(".tmp")
            tmp.write_text(json.dumps({"scanned_at": self.scanned_at, "games": self.games}, ensure_ascii=False),
                           encoding="utf-8")
            tmp.replace(self.cache_file)
        except OSError as exc:
            log.warning("кэш списка игр не записан: %s", exc)

    def snapshot(self, cfg: Dict[str, Any]) -> Dict[str, Any]:
        """Список для окна. Состояние русификации каждой игры перечитывается с диска (это быстро:
        манифест бэкапа и stat файлов) — кэш хранит только сам список игр. Иначе игра, которую с тех
        пор переустановили, обновили или откатили в обход программы, так и висит «На русском».
        Папки, которых больше нет, не показываются; скрытые игры идут с пометкой ``hidden``."""
        hidden = {library._norm(Path(p)) for p in cfg.get("library_hidden") or []}
        covers = {library._norm(Path(p)): f for p, f in (cfg.get("library_covers") or {}).items()}
        with self._lock:
            games = [dict(g) for g in self.games]
        out, fresh = [], {}
        for g in games:
            p = Path(g["path"])
            if not p.is_dir():
                continue
            key = library._norm(p)
            try:
                st = status(p)
            except Exception as exc:  # noqa: BLE001
                log.debug("состояние %s: %s", p, exc)
                st = {}
            if any(g.get(k) != v for k, v in st.items()):
                fresh[key] = st
            g.update(st)
            g["hidden"] = key in hidden
            if key in covers:
                data = cover_data(covers[key])
                if data:
                    g["cover"], g["cover_custom"] = data, True
            out.append(g)
        if fresh:
            with self._lock:
                for g in self.games:
                    st = fresh.get(library._norm(Path(g["path"])))
                    if st:
                        g.update(st)
                self._save_cache()
        return {"games": out, "scanned_at": self.scanned_at, "scanning": self.scanning}

    def refresh_status(self, path: str) -> Optional[Dict[str, Any]]:
        """Перечитать состояние игры с диска — после всего, что меняет её файлы (русификация,
        архив-русификатор, откат). Окно получает событие ``game_status`` и само обновляет список и
        открытую карточку игры. Русифицированная игра, которой нет в списке, добавляется в него."""
        p = Path(path)
        key = library._norm(p)
        st = status(p)
        with self._lock:
            game = next((g for g in self.games if library._norm(Path(g["path"])) == key), None)
            if game is None and st["russified"]:
                game = _entry(p, "russified")
                self.games.append(game)
                self.games.sort(key=lambda g: str(g.get("title", "")).lower())
            if game is None:
                return None
            game.update(st)
            self._save_cache()
            game = dict(game)
        self.emit({"type": "game_status", "game": game})
        return game

    def scan(self, cfg: Dict[str, Any]) -> bool:
        """Запустить фоновый поиск. False — поиск уже идёт."""
        with self._lock:
            if self.scanning:
                return False
            self._thread = threading.Thread(target=self._scan, args=(dict(cfg),), name="library", daemon=True)
            self._thread.start()
        return True

    def _scan(self, cfg: Dict[str, Any]) -> None:
        started = time.monotonic()
        try:
            found = library.discover(
                extra_folders=cfg.get("library_folders") or [],
                manual=cfg.get("library_manual") or [],
                russified=russified_dirs(),
                status=lambda name: self.emit({"type": "library_progress", "message": f"Ищу игры: {name}…"}))
            games = []
            for e in found:
                d = e.to_dict()
                try:
                    d.update(status(Path(e.path)))
                except Exception as exc:  # noqa: BLE001
                    log.debug("состояние %s: %s", e.path, exc)
                games.append(d)
            with self._lock:
                self.games = games
                self.scanned_at = time.time()
                self._save_cache()
            log.info("Мои игры: %d за %.1f с", len(games), time.monotonic() - started)
            self.emit({"type": "library", "final": True, **self.snapshot(cfg), "scanning": False})
        except Exception as exc:  # noqa: BLE001
            log.exception("поиск игр упал")
            self.emit({"type": "library", "final": True, "error": str(exc), **self.snapshot(cfg), "scanning": False})

    def add(self, path: str) -> Dict[str, Any]:
        p = Path(path)
        d = _entry(p, "manual")
        d.update(status(p))
        key = library._norm(p)
        with self._lock:
            self.games = [g for g in self.games if library._norm(Path(g["path"])) != key] + [d]
            self.games.sort(key=lambda g: str(g.get("title", "")).lower())
            self._save_cache()
        return d

    def forget(self, path: str) -> None:
        """Убрать запись из списка (вручную добавленную папку, которую забыли)."""
        key = library._norm(Path(path))
        with self._lock:
            self.games = [g for g in self.games if library._norm(Path(g["path"])) != key
                          or (g.get("sources") or [g.get("source")]) != ["manual"]]
            self._save_cache()


def _entry(p: Path, source: str) -> Dict[str, Any]:
    """Запись списка для папки, добавленной не поиском (вручную или русифицированной)."""
    e = library.GameEntry(path=str(p), title=p.name, source=source, engine=library.quick_engine(p))
    exe = library.main_exe(p)
    e.exe = str(exe) if exe else ""
    e.sources = [source]
    return e.to_dict()


#: своя обложка: кадрируется под карточку (460×215) и хранится уменьшенной копией
COVER_SIZE = (920, 430)


def covers_dir() -> Path:
    return paths.sub("covers")


def save_cover(src: Path, game: Path) -> str:
    """Своя обложка игры из картинки пользователя: кадр по центру под пропорции карточки, JPEG.
    Возвращает имя файла в папке обложек. Бросает ValueError, если это не картинка."""
    import hashlib
    from PIL import Image, ImageOps
    try:
        with Image.open(src) as im:
            im.seek(0)                                   # GIF/WebP с анимацией — первый кадр
            im = ImageOps.exif_transpose(im).convert("RGB")
    except Exception as exc:  # noqa: BLE001
        raise ValueError(f"Не удалось открыть картинку: {exc}") from exc
    w, h = COVER_SIZE
    crop_w = min(im.width, im.height * w / h)            # сколько пикселей картинки войдёт в кадр
    scale = min(1.0, crop_w / w)                         # маленькую не растягиваем
    im = ImageOps.fit(im, (max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
    name = hashlib.sha1(library._norm(Path(game)).encode("utf-8")).hexdigest()[:16] + ".jpg"
    tmp = covers_dir() / (name + ".tmp")
    im.save(tmp, "JPEG", quality=86, optimize=True)
    tmp.replace(covers_dir() / name)
    return name


def cover_data(name: str) -> str:
    """Своя обложка как data-URL (окно не читает файлы с диска само)."""
    import base64
    if not re.fullmatch(r"[0-9a-f]{16}\.jpg", name or ""):
        return ""
    try:
        return "data:image/jpeg;base64," + base64.b64encode((covers_dir() / name).read_bytes()).decode("ascii")
    except OSError:
        return ""


def steam_cover_file(appid: str) -> Optional[Path]:
    """Обложка из кэша Steam (работает без интернета)."""
    root = library.steam_root()
    if root is None or not re.fullmatch(r"\d+", appid or ""):
        return None
    cache = root / "appcache" / "librarycache"
    for p in (cache / f"{appid}_header.jpg", cache / appid / "header.jpg", cache / f"{appid}_library_hero.jpg"):
        if p.is_file():
            return p
    d = cache / appid
    if d.is_dir():
        for p in d.rglob("header*.jpg"):
            return p
    return None
