ProgressFn = Callable[[str, Optional[float]], None]


def _noop(message: str, fraction: Optional[float] = None) -> None:
    pass


# ---------- что найдено во время игры ----------

def live_lines(game_root: Path) -> Dict[str, str]:
    """Строки, переведённые в игре на лету (файл XUnity)."""
    return xunity.read_translations(Path(game_root) / LIVE_FILE)


def load_found(work_dir: Path) -> Dict[str, Dict[str, str]]:
    """Сохранённые в проекте строки, найденные во время игры: текст -> {translation, seen}."""
    try:
        data = json.loads((Path(work_dir) / FOUND_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return {k: v for k, v in data.items() if isinstance(k, str) and isinstance(v, dict)} \
        if isinstance(data, dict) else {}


def harvest(game_root: Path, work_dir: Path) -> int:
    """Перенести найденное во время игры из файла XUnity в проект (перед откатом и новой русификацией).
    Возвращает, сколько строк теперь сохранено в проекте."""
    lines = live_lines(game_root)
    store = load_found(work_dir)
    if not lines:
        return len(store)
    today = time.strftime("%Y-%m-%d")
    added = 0
    for src, tr in lines.items():
        if src not in store:
            store[src] = {"translation": tr, "seen": today}
            added += 1
    if added:
        path = Path(work_dir) / FOUND_FILE
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(json.dumps(store, ensure_ascii=False, indent=0), encoding="utf-8")
        tmp.replace(path)
        log.info("найденное во время игры сохранено в проекте: +%d (всего %d)", added, len(store))
    return len(store)


def worth_translating(text: str, translation: str = "") -> bool:
    """Строку, найденную во время игры, стоит включить в словарь: это текст для игрока (живой перевод
    не вернул её как есть — имя, код, журнал, название площадки)."""
    s = text.strip()
    return (bool(s) and len(s) <= xunity.MAX_CHARS and translation.strip() != s and looks_translatable(s)
            and not looks_technical(s) and not is_brand(s))


def missed(game_root: Path, work_dir: Path) -> Dict[str, str]:
    """Всё, что поиск при русификации пропустил: найденное во время игры (в файле игры и в проекте)."""
    out = {k: v.get("translation", "") for k, v in load_found(work_dir).items()}
    out.update(live_lines(game_root))
    return out


# ---------- где лежит пропущенная строка ----------

_TAG_RE = re.compile(r"<[^<>]{1,60}>")
_FMT_RE = re.compile(r"\{\d+(?:,-?\d+)?(?::[^{}]*)?\}")


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", _TAG_RE.sub(" ", s)).strip()


@dataclass
class Miss:
    text: str
    translation: str
    kind: str          # ключ KINDS
    where: str = ""    # где нашлась строка (или её части)
    note: str = ""     # почему поиск её отбросил


class _Index:
    """Все строки игры до отбора: точные, нормализованные и шаблоны «{0}»."""

    MAX_TEMPLATES = 4000

    def __init__(self, seen: Dict[str, str]):
        self.exact = seen
        self.norm: Dict[str, str] = {}
        for s, origin in seen.items():
            self.norm.setdefault(_norm(s), origin)
        self.templates: List[Tuple["re.Pattern", str, str]] = []
        for s, origin in seen.items():
            if len(self.templates) >= self.MAX_TEMPLATES:
                break
            if not _FMT_RE.search(s) or len(s) > 300 or not re.search(r"[A-Za-z]{3}", _FMT_RE.sub("", s)):
                continue
            parts = _FMT_RE.split(_norm(s))
            rx = "".join(re.escape(p) + ("(.+?)" if i < len(parts) - 1 else "") for i, p in enumerate(parts))
            try:
                self.templates.append((re.compile("^" + rx + "$", re.S), s, origin))
            except re.error:
                continue

    def find(self, text: str) -> Optional[str]:
        return self.exact.get(text) or self.norm.get(_norm(text))

    def template(self, text: str) -> Optional[Tuple[str, str]]:
        t = _norm(text)
        for rx, src, origin in self.templates:
            if rx.match(t):
                return src, origin
        return None

    def covered(self, part: str, depth: int = 0) -> Optional[str]:
        """Кусок строки есть в данных — целиком или как «известное + известное» по границе слов."""
        hit = self.find(part)
        if hit or depth >= 3:
            return hit
        words = part.split(" ")
        for i in range(1, len(words)):
            left, right = " ".join(words[:i]), " ".join(words[i:])
            a = self.find(left)
            if a:
                b = self.covered(right, depth + 1)
                if b:
                    return a if a == b else f"{a}, {b}"
        return None


def _parts(text: str) -> List[str]:
    """Кусочки, из которых игра могла склеить строку: строки, текст между тегами, без чисел и знаков."""
    plain = _TAG_RE.sub("\n", text)
    out = []
    for p in re.split(r"[\r\n]+|\s*[+=×x%]?\d[\d.,:]*%?\s*|\s+[+=]|\s*[|•·]\s*", plain):
        p = p.strip(" :+-=()[]{}.,!?/")
        if len(re.findall(r"[A-Za-z]", p)) >= 2:
            out.append(p)
    return out


def _why_filtered(text: str, origin: str) -> str:
    s = text.strip()
    if looks_technical(s):
        return "похожа на журнал, путь или команду"
    if not looks_translatable(s, strict=True):
        return "похожа на служебную строку (одно слово с маленькой буквы, идентификатор, цифры)"
    if not looks_like_sentence(s):
        return ("короткая подпись в поле, которое поиск не считает текстом" if origin != "code"
                else "короткая строка из кода: из кода берутся фразы и подписи с заглавной")
    return "отброшена фильтром"


def classify(texts: Dict[str, str], seen: Dict[str, str], found: Optional[set] = None) -> List[Miss]:
    """Разложить пропущенные строки по видам (см. KINDS) по всем строкам игры до отбора ``seen``;
    ``found`` — что нынешний поиск уже берёт в словарь."""
    idx = _Index(seen)
    found = found or set()
    out: List[Miss] = []
    for text, tr in texts.items():
        origin = idx.find(text)
        if text in found:
            out.append(Miss(text, tr, "found", origin or ""))
            continue
        if origin and _NAMES_RE.search(origin):
            out.append(Miss(text, tr, "names", origin))
            continue
        if (tr and tr.strip() == text.strip()) or (not worth_translating(text, tr) and not looks_like_sentence(text)):
            out.append(Miss(text, tr, "skip", origin or ""))
            continue
        if origin:
            kind = "names" if _NAMES_RE.search(origin) else "filtered"
            out.append(Miss(text, tr, kind, origin, "" if kind == "names" else _why_filtered(text, origin)))
            continue
        tpl = idx.template(text)
        if tpl:
            out.append(Miss(text, tr, "template", f"{tpl[1]}: «{tpl[0][:80]}»"))
            continue
        parts = _parts(text)
        pieces = [(p, idx.covered(p)) for p in parts]
        have = [(p, w) for p, w in pieces if w]
        where = "; ".join(sorted({w for _, w in have}))[:300]
        if parts and len(have) == len(parts) and (len(parts) > 1 or _norm(parts[0]) != _norm(text)):
            out.append(Miss(text, tr, "composed", where))
        elif have:
            missing = [p for p, w in pieces if not w][:4]
            out.append(Miss(text, tr, "partly", where, "не найдено: " + "; ".join(f"«{m[:40]}»" for m in missing)))
        else:
            out.append(Miss(text, tr, "absent"))
    order = list(KINDS)
    out.sort(key=lambda m: (order.index(m.kind), m.text.lower()))
    return out


def seen_strings(game, progress: ProgressFn = _noop) -> Tuple[Dict[str, str], set]:
    """Все строки данных и кода игры до отбора (тот же разбор, что при русификации) и те из них,
    что поиск берёт в словарь."""
    from . import extract
    col = extract._Collector()
    col.seen = {}
    extract.extract_assets(game, col, [], progress)
    progress("Текстовые файлы игры…", None)
    extract.extract_loose_files(game, col)
    progress("Строки из кода игры…", None)
    extract.extract_code_strings(game, col, [])
    return col.seen, set(col.items)


def diagnose(game_root: Path, work_dir: Path, progress: ProgressFn = _noop) -> Dict:
    """Отчёт о полноте перевода: что пропущено и почему. Сохраняется в папке проекта."""
    from . import detect
    game_root = Path(game_root)
    texts = missed(game_root, work_dir)
    report: Dict = {"game": game_root.name, "date": time.strftime("%Y-%m-%d %H:%M"), "total": len(texts),
                    "counts": {}, "items": []}
    if texts:
        game = detect.inspect(game_root)
        seen, found = seen_strings(game, progress) if game is not None else ({}, set())
        items = classify(texts, seen, found)
        report["items"] = [asdict(m) for m in items]
        for m in items:
            report["counts"][m.kind] = report["counts"].get(m.kind, 0) + 1
    report["kinds"] = {k: {"title": t, "about": a} for k, (t, a) in KINDS.items()}
    try:
        Path(work_dir).mkdir(parents=True, exist_ok=True)
        txt = Path(work_dir) / REPORT_TXT
        report["file"] = str(txt)
        txt.write_text(format_report(report), encoding="utf-8")
        (Path(work_dir) / REPORT_JSON).write_text(json.dumps(report, ensure_ascii=False), encoding="utf-8")
    except OSError as exc:
        log.warning("отчёт о полноте не сохранён: %s", exc)
    return report


def last_report(work_dir: Path) -> Optional[Dict]:
    try:
        return json.loads((Path(work_dir) / REPORT_JSON).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def format_report(report: Dict) -> str:
    """Отчёт обычным текстом (для файла и командной строки)."""
    lines = [f"Полнота перевода: {report.get('game', '')} ({report.get('date', '')})", ""]
    total = report.get("total", 0)
    if not total:
        lines.append("Во время игры живому переводу ничего не досталось — всё, что игра показала, было в словаре.")
        return "\n".join(lines) + "\n"
    lines.append(f"Игра показала {total} строк, которых не было в заранее подготовленном словаре. Они уже "
                 "переводятся на лету, войдут в архив-русификатор и при следующей русификации — в основной словарь.")
    items = report.get("items", [])
    for kind, (title, about) in KINDS.items():
        group = [m for m in items if m["kind"] == kind]
        if not group:
            continue
        lines += ["", f"== {title}: {len(group)}", about]
        for m in group:
            text = m["text"].replace("\n", "\\n")
            lines.append(f"  • {text[:200]}")
            if m.get("where"):
                lines.append(f"      где: {m['where']}")
            if m.get("note"):
                lines.append(f"      {m['note']}")
    return "\n".join(lines) + "\n"
