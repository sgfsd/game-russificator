"""Полнота перевода Unity-игры: что игра показала на экране, а заранее найдено не было.

Строки, которых нет в заранее подготовленном словаре, XUnity отправляет живому переводу, а
результат сам дописывает в ``BepInEx/Translation/ru/Text/_AutoGeneratedTranslations.txt``. Значит,
этот файл — ровно список того, что поиск текста при русификации пропустил.

Здесь он используется дважды:

* :func:`harvest` — перед повторной русификацией и откатом файл сохраняется в папке проекта
  (``live_found.json``): откат удаляет папку BepInEx вместе с ним, и всё найденное во время игры
  пропадало. Сохранённые строки при следующей русификации входят в основной словарь — значит, и в
  русификатор «для друзей», где живого перевода нет;
* :func:`diagnose` — для каждой пропущенной строки ищет, где она лежит в файлах игры: игра ещё раз
  разбирается тем же поиском, что и при русификации, но запоминаются все строки до отбора. Так видно,
  отбросил ли её фильтр (и почему), собрала ли игра её из кусочков, или в данных её нет вовсе — по
  этому видно, какую дыру в поиске закрывать.
"""

