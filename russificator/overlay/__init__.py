"""Живой перевод поверх игры (оверлей): распознать текст на экране и показать перевод.

Работает отдельным процессом (``Russificator.exe --overlay``) с иконкой в трее:
включили один раз — и дальше, пока идёт игра, её иностранный текст переводится
сам. Файлы игры не трогаются, поэтому подходит для любых движков, Game Pass и
лицензионных копий.

Модули:
  * ``text``    — строки распознавания → блоки текста, фильтр «иностранное»,
                  устойчивость (текст, печатающийся по буквам, дожидаемся);
  * ``render``  — картинка оверлея: плашки с переводом поверх оригинала;
  * ``detect``  — игра ли сейчас на экране (списки, «Мои игры», Game Bar, полный экран);
  * ``win32``   — окна, захват экрана, прозрачное окно, трей, горячие клавиши (ctypes);
  * ``ocr``     — распознавание текста Windows (Windows.Media.Ocr через pythonnet);
  * ``service`` — главный цикл, перевод в фоне, состояние для окна программы.
"""

